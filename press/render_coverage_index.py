#!/usr/bin/env python3
"""
render_coverage_index.py — the COVERAGE INDEX page (owner order 2026-08-01):
every frozen logic unit, in canonical order, with a per-book verse meter and
switch links both ways (YAML view <-> verse tree/morph view in the scroll).

Derived artifact only (Pre-Code): reads derivation.sqlite (units/steps/verses,
themselves indexed from the canonical YAML) and writes UNIT_INDEX.html beside
the per-unit pages. Regenerated by dev_server's /regen/data chain.

Usage:  python3 render_coverage_index.py
"""
import html
import re
import sqlite3
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DB = ROOT / "data" / "derivation.sqlite"
OUT = HERE / "UNIT_INDEX.html"

BOOK_IDS = {"Genesis": "Gen", "Exodus": "Exod", "Leviticus": "Lev",
            "Numbers": "Num", "Deuteronomy": "Deut"}
BOOK_ORD = {"Genesis": 1, "Exodus": 2, "Leviticus": 3, "Numbers": 4, "Deuteronomy": 5}


def esc(x):
    return html.escape("" if x is None else str(x))


def ref_key(refs):
    mt = re.match(r"(\d+):(\d+)", refs or "")
    return (int(mt.group(1)), int(mt.group(2))) if mt else (999, 999)


def main():
    cx = sqlite3.connect(DB)
    units = cx.execute(
        "SELECT unit_id, book_en, refs, title_en, n_steps, n_scenarios "
        "FROM units WHERE status='frozen'").fetchall()
    units.sort(key=lambda r: (BOOK_ORD.get(r[1], 9), ref_key(r[2])))

    # verse counts: derived (distinct step refs of frozen units) vs book totals
    derived = {}
    for uid, book, *_ in units:
        rows = cx.execute("SELECT DISTINCT ref FROM steps WHERE unit_id=?", (uid,)).fetchall()
        derived.setdefault(book, set()).update(r[0] for r in rows)
    totals = dict(cx.execute("SELECT book, COUNT(*) FROM verses GROUP BY book"))

    S = []
    S.append("<h1>Derived coverage — all frozen logic units</h1>")
    S.append('<div class="meta">generated %s from derivation.sqlite (indexed from '
             "the canonical YAML in logic/units/) · "
             '<a href="/">⇄ open the scroll (verse tree + morph view)</a></div>'
             % date.today().isoformat())

    S.append("<h2>Coverage meters</h2><table>")
    S.append("<tr><th>book</th><th>verses derived</th><th>of</th><th>meter</th></tr>")
    for book in sorted(derived, key=lambda b: BOOK_ORD.get(b, 9)):
        bid = BOOK_IDS.get(book, book)
        n = len(derived[book])
        tot = totals.get(bid, 0)
        pct = 100.0 * n / tot if tot else 0
        bar = "█" * int(round(pct / 2)) + "░" * (50 - int(round(pct / 2)))
        S.append('<tr><td><b>%s</b></td><td>%d</td><td>%d</td>'
                 '<td class="code">%s %.1f%%</td></tr>'
                 % (esc(book), n, tot, bar, pct))
    S.append("</table>")

    S.append("<h2>Units, in canonical order</h2><table>")
    S.append("<tr><th>span</th><th>unit</th><th>title</th><th>steps</th>"
             "<th>scenarios</th><th>views</th></tr>")
    audited = 0
    for uid, book, refs, title, n_steps, n_scen in units:
        bid = BOOK_IDS.get(book, book)
        mt = re.match(r"(\d+):(\d+)", refs or "")
        verse_link = ('<a href="/#%s/%s/%s">verse view</a>' %
                      (bid, mt.group(1), mt.group(2))) if mt else ""
        # oral-first era (2026-08-08): link the unit's oral-audit page when
        # one has been rendered (retro program, PROCESS.md)
        audit_link = ""
        if (HERE / ("ORAL_AUDIT_%s.html" % uid)).exists():
            audited += 1
            audit_link = (' · <a href="ORAL_AUDIT_%s.html" class="audit">'
                          '&#10003; oral audit</a>' % uid)
        S.append('<tr id="unit-%s"><td><b>%s %s</b></td>'
                 '<td class="code"><a href="UNIT_%s.html">%s</a></td>'
                 '<td>%s</td><td>%s</td><td>%s</td>'
                 '<td><a href="UNIT_%s.html">YAML view</a> · %s%s</td></tr>'
                 % (esc(uid), esc(book), esc(refs), esc(uid), esc(uid),
                    esc(title), n_steps, n_scen, esc(uid), verse_link,
                    audit_link))
    S.append("</table>")
    S.append('<div class="meta">Oral-audit retro program (PROCESS.md, '
             "oral-first era): %d of %d frozen units audited — "
             "&#10003; marks a unit whose crowns are chain-attested + "
             "DB-verified and folded in.</div>" % (audited, len(units)))
    S.append('<div class="note">Experimental model — not binding religious law. '
             "The YAML in logic/units/ is canonical; this page and the per-unit "
             "pages are derived artifacts, regenerated on demand.</div>")

    page = """<!doctype html><html><head><meta charset="utf-8">
<title>Derived coverage — TorahSim</title>
<style>
body { font: 15px/1.55 Georgia, serif; max-width: 1100px; margin: 2rem auto;
       padding: 0 1rem; color: #232019; background: #fbfaf6; }
h1 { font-size: 1.5rem; } h2 { font-size: 1.1rem; margin-top: 2rem; }
table { border-collapse: collapse; width: 100%%; font-size: .92rem; }
th, td { border: 1px solid #ddd6c3; padding: .35rem .55rem; text-align: left;
         vertical-align: top; }
th { background: #f0ecdf; font-size: .8rem; text-transform: uppercase; }
.code { font-family: ui-monospace, monospace; font-size: .84rem; }
.meta { color: #6b6455; font-size: .9rem; }
.note { background: #f7f5ee; border: 1px solid #e3ddc9; padding: .6rem .8rem;
        margin-top: 1.5rem; font-size: .9rem; }
a { color: #4a6da7; }
a.audit { color: #0a7a2f; font-weight: bold; text-decoration: none; }
</style></head><body>%s</body></html>""" % "\n".join(S)
    OUT.write_text(page, encoding="utf-8")
    print("wrote %s (%d units)" % (OUT.name, len(units)))


if __name__ == "__main__":
    main()
