"""
machine.py — the six-register machine as a plain Python library.

This module backs the GENERATED per-unit Python renderings in this
directory (logic/py_units/<unit_id>.py). Contract:

  * Pre-Code holds: the FROZEN YAML in logic/units/ is the ONLY canonical
    logic. These Python files are derived renderings — generated by
    logic/pre_logic_methods_2026-07-28/render_unit_py.py from frozen units,
    never hand-edited, always regenerable.
  * Semantics here MIRROR run_unit.py (the Stage D interpreter) handler for
    handler. Fidelity is enforced mechanically: every generated unit file
    ends with assertions baked from the interpreter's actual final state at
    generation time — if this module ever drifts from run_unit.py, the
    generated files go red.
  * Registers: TIME / WORLD / REGISTRY / SPECS / TESTS / LEDGER + FLAGS
    side channel (and EVENTS / TRIPLES logs).
  * Flags never auto-resolve. Verdicts are data. LET? never auto-upgrades
    (TIR-028); LET-NOT has no resolution path at all (TIR-034 contract).

Hebrew glossing rule (owner order, absolute): every transliterated Hebrew
word in the generated files is paired with English inline.
"""


class Machine:
    def __init__(self, unit_id=""):
        self.unit_id = unit_id
        self.TIME = {"t0": None, "marks": []}
        self.WORLD = {"entities": {}, "facts": [], "invariants": [], "partitions": []}
        self.REGISTRY = {"names": {}, "writes": 0}
        self.SPECS = {"queue": [], "log": []}
        self.TESTS = []
        self.LEDGER = {}
        self.FLAGS = []
        self.EVENTS = []
        self.TRIPLES = []
        self._step_ref = None
        self._step_event_mark = 0

    # -- step boundary (one call per verse in the generated files) -----------
    def step(self, ref):
        self._step_ref = ref
        self._step_event_mark = len(self.EVENTS)

    # -- core helpers (mirror run_unit.Machine) -------------------------------
    def _install(self, name, mode, by):
        ent = self.WORLD["entities"].get(name)
        if ent is None:
            self.WORLD["entities"][name] = {"mode": mode, "by": by,
                                            "step": self._step_ref}
        elif ent["mode"] == "presupposed" and mode == "created":
            ent.update(mode="created", by=by, step=self._step_ref)

    def flag(self, kind, detail):
        self.FLAGS.append({"kind": kind, "detail": detail, "step": self._step_ref})

    def event(self, verb, agent=None, themes=()):
        self.EVENTS.append({"verb": verb, "agent": agent,
                            "themes": list(themes), "step": self._step_ref})

    # -- operators (one method per YAML op kind) ------------------------------
    def time_anchor(self, x):                        # TIME_ANCHOR: t0 := x
        self.TIME["t0"] = x

    def install(self, *names):                       # REGISTRY_INSTALL: WORLD += {..}
        for n in names:
            self._install(n, "created", "narration")

    def fact(self, *facts):                          # PRECONDITION_STATE: HOLDS(p, tN)
        for f in facts:
            self.WORLD["facts"].append(f)

    def invariant(self, p):                          # INVARIANT(p) during tN
        self.WORLD["invariants"].append(p)

    def presupposed(self, *names):                   # NOTE_PRESUPPOSED: read, not made
        for n in names:
            self._install(n, "presupposed", "read-before-install")
            self.flag("read_before_install", n)

    def note_zero_events(self):                      # NOTE_ZERO_EVENTS
        fired = len(self.EVENTS) - self._step_event_mark
        assert fired == 0, ("unit claims zero events in %s but %d fired"
                            % (self._step_ref, fired))

    def spec_delta(self, spec, delivered):           # NOTE_SPEC_DELTA
        self.flag("spec_delta", "spec '%s' -> delivered '%s'" % (spec, delivered))

    def declare(self, speaker, mood, demand):        # DECLARE(x, MOOD(demand))
        entry = {"demand": demand, "mood": mood, "speaker": speaker,
                 "pushed_step": self._step_ref, "satisfied_step": None,
                 "resolution_cite": None}
        self.SPECS["queue"].append(entry)
        self.SPECS["log"].append(entry)
        self.event("declare", speaker, [demand])

    def triple(self, q):                             # TRIPLE { Q: .. }
        self.TRIPLES.append({"q": q, "step": self._step_ref, "discharged": False})

    def result(self, q, tmark=None):                 # RESULT: HOLDS(q, tN) — the receipt
        if tmark:
            self.TIME["marks"].append(tmark)
        for entry in list(self.SPECS["queue"]):
            if entry["demand"] == q:
                entry["satisfied_step"] = self._step_ref
                self.SPECS["queue"].remove(entry)
                break
        import re as _re
        em = _re.search(r"exists\((\w+)\)", q)
        if em:
            self._install(em.group(1), "created", "fiat-result")
        for tr in self.TRIPLES:
            if not tr["discharged"] and tr["q"] == q:
                tr["discharged"] = True
        self.event("result", None, [q])

    def test(self, verdict, oracle, theme):          # TEST: PASS|FAIL(a, b)
        self.TESTS.append({"oracle": oracle, "theme": theme,
                           "verdict": verdict, "step": self._step_ref})

    def partition(self, a, b):                       # EVENT_PARTITION: between(a, b)
        self.WORLD["partitions"].append((a, b))
        self.event("divide", None, [a, b])

    def name(self, ent, label):                      # NAME: name(x) := y
        if ent not in self.WORLD["entities"]:
            self.flag("named_before_any_presence", ent)
        self.REGISTRY["names"][ent] = label
        self.REGISTRY["writes"] += 1
        self.event("name", None, [ent, label])

    def assign(self, ent, role):                     # ASSIGN: REGISTRY: x->role
        if ent not in self.WORLD["entities"]:
            self.flag("assigned_before_any_presence", ent)
        self.REGISTRY["names"][ent] = role
        self.REGISTRY["writes"] += 1
        self.event("assign", None, [ent, role])

    def bless(self, speaker, recipients, mandate=()):  # BLESS [MANDATE {..}]
        for item in mandate:
            self.WORLD["facts"].append("mandate: %s" % item)
        self.event("bless", speaker, [recipients] + list(mandate))

    def case(self, subject_filter, route):           # CASE(..) ROUTE(x)
        self.WORLD["facts"].append("case: %s -> %s" % (subject_filter, route))
        self.event("case_installed", None, [route])

    def handler(self, cond, then):                   # HANDLER IF(..) THEN(..)
        self.WORLD["facts"].append("handler: IF(%s) THEN(%s)" % (cond, then))
        self.event("handler_installed", None, [cond[:40]])

    def pattern(self, p):                            # PATTERN(p) — al-ken etiology
        self.WORLD["facts"].append("pattern: %s" % p)
        self.event("pattern_installed", None, [p[:40]])

    def statute(self, polarity, payload):            # STATUTE FORBID(x)/BIND(x) — lev_19
        self.WORLD["facts"].append("statute: %s(%s)" % (polarity, payload))
        self.event("statute_installed", None, [payload[:40]])

    def section(self, label, *members):              # SECTION — labels, installs nothing
        self.event("section", None, [label] + list(members))

    def commit(self, day, label_form=None, label_he="", label_translit=""):
        spec_ok = (not self.SPECS["queue"]
                   and all(e["satisfied_step"] for e in self.SPECS["log"]))
        test_pass = any(t["verdict"] == "PASS" for t in self.TESTS)
        if not test_pass:
            self.flag("commit_without_test",
                      "day %d cycle closed with TESTS empty" % day)
        self.LEDGER[day] = {"closed": True, "spec_ok": spec_ok,
                            "test_pass": test_pass,
                            "names": self.REGISTRY["writes"],
                            "label_form": label_form, "label_he": label_he,
                            "label_translit": label_translit,
                            "step": self._step_ref}

    # -- summaries for the baked assertions -----------------------------------
    def created_set(self):
        return {n for n, e in self.WORLD["entities"].items() if e["mode"] == "created"}

    def presupposed_set(self):
        return {n for n, e in self.WORLD["entities"].items()
                if e["mode"] == "presupposed"}

    def open_demands(self):
        return [e["demand"] for e in self.SPECS["queue"]]

    def tests_list(self):
        return [(t["verdict"], t["oracle"], t["theme"]) for t in self.TESTS]

    def flag_counts(self):
        out = {}
        for f in self.FLAGS:
            out[f["kind"]] = out.get(f["kind"], 0) + 1
        return out

    def report(self):
        print("unit: %s (python rendering — YAML is canonical)" % self.unit_id)
        print("WORLD: created=%s (+%d presupposed) | facts=%d | invariants=%d"
              % (sorted(self.created_set()), len(self.presupposed_set()),
                 len(self.WORLD["facts"]), len(self.WORLD["invariants"])))
        print("REGISTRY: %s (%d writes)" % (self.REGISTRY["names"],
                                            self.REGISTRY["writes"]))
        print("SPECS: %d open %s | %d total" % (len(self.SPECS["queue"]),
                                                self.open_demands(),
                                                len(self.SPECS["log"])))
        print("TESTS: %s | LEDGER days: %s" % (self.tests_list(),
                                               sorted(self.LEDGER)))
        print("FLAGS: %s | EVENTS: %d" % (self.flag_counts(), len(self.EVENTS)))
