#!/usr/bin/env python3
# 13b docket D1 — the 12b docket instruments derived by ASSERTED substitutions (each old string counted before it is replaced): ch14_credit_carry.py -> ch15_credit_carry.py,
# ch14_docket_common.py -> ch15_docket_common.py (+ the two-run split BY ADDRESS appended — the design's D1/D2 are sets, not index ranges), ch14_docket_rows.py -> ch15_docket_rows.py.
import os, subprocess
ROOT = subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], text=True).strip()
SP = os.path.dirname(os.path.abspath(__file__)); F = f'{ROOT}/World/step9/forms_deuteronomy_walk'
def derive(src, dst, subs, extra=''):
    t = open(f'{F}/{src}', encoding='utf-8').read()
    for old, new, n in subs:
        c = t.count(old); assert c == n, (src, old[:60], c, n); t = t.replace(old, new)
    assert 'ch14' not in t.replace('ch14_', '\x00') or 'ch14_' not in t, (dst, 'a ch14 name survives')
    open(f'{SP}/{dst}', 'w', encoding='utf-8').write(t + extra); print('WROTE', dst, len((t + extra).encode()), 'bytes', len(subs), 'substitutions')
derive('ch14_credit_carry.py', 'ch15_credit_carry.py', [
 ("# 12b docket (11b's form) — THE CREDITED ROWS", "# 13b docket (12b's form) — THE CREDITED ROWS", 1),
 ('ch14_docket_dump.txt', 'ch15_docket_dump.txt', 1),
 ('ch14_credited_rows.py', 'ch15_credited_rows.py', 2),
 ('ch14_uncred_unres.txt', 'ch15_uncred_unres.txt', 2),
 (r"# 12b docket — THE CREDITED ROWS CARRIED WITH THEIR LEDGERS, generated by ch14_credit_carry.py (11b\'s form", r"# 13b docket — THE CREDITED ROWS CARRIED WITH THEIR LEDGERS, generated by ch15_credit_carry.py (12b\'s form", 1),
])
SPLIT = '''
# 13b — THE TWO DOCKET RUNS BY ADDRESS (the design: D1 every address outside the two long ranges; D2 Kiddushin 14b-22b and Bekhorot 25a-28b WITH THEIR OWN LINK ROWS) —
# the sets computed from the dump, never typed; a part builds over a SUBSET of D1 (build_set) and the writer checks every address of the dump is verdicted once.
import re as _re
def long_range(a):
    m = _re.match(r'(Kiddushin|Bekhorot) (\\d+)([ab]):\\d+$', a)
    if not m: return None
    w, f, s = m.group(1), int(m.group(2)), m.group(3)
    if w == 'Kiddushin' and ((f == 14 and s == 'b') or 15 <= f <= 22): return 'Kiddushin 14b-22b'
    if w == 'Bekhorot' and 25 <= f <= 28: return 'Bekhorot 25a-28b'
    return None
D1 = [a for a in ADDRS if long_range(a) is None]
D2 = [a for a in ADDRS if long_range(a) is not None]
assert len(D1) + len(D2) == len(ADDRS)
def build_set(spec, addrs):
    rows, unmatched = [], []
    for a in addrs:
        for key, verdict, note in spec:
            if (key == a) if isinstance(key, str) else key(a):
                rows.append((a, verdict, note)); break
        else:
            unmatched.append(a)
    assert not unmatched, ('UNMATCHED', unmatched[:20], len(unmatched))
    return rows
'''
derive('ch14_docket_common.py', 'ch15_docket_common.py', [
 ("THE DEUTERONOMY WALK 12b (11b's form by derive_ch14_docket_tools.py)", "THE DEUTERONOMY WALK 13b (12b's form by derive_ch15_docket_tools.py)", 1),
 ('cold_run_food_tithe.py (F1 the_sons_and_the_cuttings, F2 the_beasts, F3 the_water_and_the_birds, F4 the_carcass_and_the_kid,', 'cold_run_release_firstborn.py (F1 the_release, F2 the_needy_and_the_blessing, F3 the_hand_opened, F4 the_hebrew_slave,', 1),
 ("# F5 the_second_tithe, F6 the_far_place_the_money_the_rejoicing_and_the_levite, F7 the_third_year — the design's", "# F5 the_awl_and_the_double_hire, F6 the_firstling, F7 the_blemish_and_the_blood — the design's", 1),
 ('ch14_docket_dump.txt', 'ch15_docket_dump.txt', 1),
 ("from ch14_credited_rows import CREDITED_SPEC   # 12b: the credited rows carried with their ledgers (ch14_credit_carry.py — 11b's form)", "from ch15_credited_rows import CREDITED_SPEC   # 13b: the credited rows carried with their ledgers (ch15_credit_carry.py — 12b's form)", 1),
], extra=SPLIT)
derive('ch14_docket_rows.py', 'ch15_docket_rows.py', [('ch14_docket_dump.txt', 'ch15_docket_dump.txt', 1)])
