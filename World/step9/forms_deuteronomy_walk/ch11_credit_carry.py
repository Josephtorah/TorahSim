#!/usr/bin/env python3
# 9b docket — THE CREDITED ROWS CARRIED WITH THEIR LEDGERS (THE WHOLE-ROW RULE: a credited row was read whole at its own docket; here it is LISTED with
# its ledger and the ledger's own verdict line): for each address the dump marks CREDITED, the crediting ledgers are searched in the dump's order for a
# verdict line in the exam-docket form ('- Addr [..] — VERDICT. note') or the topic-docket form ('- Addr — VERDICT. note'); a verdict among the five is
# CARRIED with the ledger's whole note; the rest are UNRESOLVED (a form without one of the five verdicts) and are read whole here. Writes
# ch11_credited_rows.py (CREDITED_SPEC in dump order) and ch11_uncred_09.txt (the unresolved rows whole); prints the counts.
import re, os, subprocess
from collections import Counter
ROOT = subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], text=True).strip()
SP = os.path.dirname(os.path.abspath(__file__))
dump = open(f'{SP}/ch11_docket_dump.txt', encoding='utf-8').read()
blocks = dump.split('\n## ')[1:]
CRED, ORDER, TEXT = {}, [], {}
for blk in blocks:
    head, _, body = blk.partition('\n')
    m = re.match(r'\[(LINK|TOPIC)\] (.+?)  (.*)$', head); kind, addr, rest = m.group(1), m.group(2).strip(), m.group(3)
    c = re.search(r'\{CREDITED: (.*?)\}', rest)
    if c: CRED[addr] = [x.strip() for x in c.group(1).split(',')]; ORDER.append((kind, addr)); TEXT[addr] = ' '.join(body.split())
FIVE = ('LAW', 'DERIVATION', 'DISPUTE', 'CONTEXT', 'OUTSIDE')
cache = {}
def ledger_text(l):
    if l not in cache:
        p = f'{ROOT}/logic/oral_triage/{l}'; cache[l] = open(p, encoding='utf-8').read() if os.path.exists(p) else None
    return cache[l]
def lookup(addr, l):
    t = ledger_text(l)
    if t is None: return None
    ea = re.escape(addr); alt = '|'.join(FIVE)
    for pat in (rf'^- {ea} \[[^\]]*\] — ({alt})\. (.*)$', rf'^- {ea} — ({alt})\. (.*)$'):
        m = re.search(pat, t, re.M)
        if m: return m.group(1), m.group(2).strip()
    return None
resolved, unresolved = {}, []
for kind, addr in ORDER:
    hit = None
    for l in CRED[addr]:
        r = lookup(addr, l)
        if r: hit = (l, r[0], r[1]); break
    if hit: resolved[addr] = hit
    else: unresolved.append((kind, addr))
out = ['# 9b docket — THE CREDITED ROWS CARRIED WITH THEIR LEDGERS, generated by ch11_credit_carry.py (never typed): (address, the crediting ledger\'s own verdict,',
       '# "CREDITED (<ledger>; carried) — <the ledger\'s whole note>") in the dump\'s order; the unresolved credited rows (a ledger form without one of the five verdicts) are read whole in the parts.',
       'CREDITED_SPEC = [']
for kind, addr in ORDER:
    if addr in resolved:
        l, v, n = resolved[addr]; n = n.replace('the halakha per R. Akiva', 'the halakha (the ruling) per R. Akiva'); out.append(f' ({addr!r}, {v!r}, {("CREDITED (" + l + "; carried) — " + n)!r}),')
out.append(']'); out.append(f'UNRESOLVED = {[a for _, a in unresolved]!r}')
open(f'{SP}/ch11_credited_rows.py', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
lines = ['%s %s %s | %s' % ('U', kind[0], addr, TEXT[addr]) for kind, addr in unresolved]
open(f'{SP}/ch11_uncred_09.txt', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('credited', len(ORDER), 'resolved', len(resolved), 'unresolved', len(unresolved), 'unresolved bytes', sum(len(x.encode()) for x in lines))
print('by verdict', dict(Counter(v for _, v, _ in resolved.values())))
print('by ledger', dict(Counter(l for l, _, _ in resolved.values()).most_common()))
print('UNRESOLVED:', '; '.join(f'{a} <{", ".join(CRED[a])}>' for _, a in unresolved))
